//! High-performance, zero-allocation 5x7 bitmap font engine for HyperShot UI.
//! Supports complete printable ASCII range (32..=126) for razor-sharp labels, badges, and tooltips.

/// Renders an ASCII text string directly into a 32-bit BGRA buffer.
pub fn render_text_to_buffer(
    buffer: &mut [u32],
    stride: u32,
    max_h: u32,
    text: &str,
    start_x: i32,
    start_y: i32,
    color: u32,
) {
    let mut cur_x = start_x;
    for ch in text.chars() {
        let bitmap = get_char_5x7(ch);
        for (row, byte) in bitmap.iter().enumerate() {
            for col in 0..5 {
                if (byte & (1 << (4 - col))) != 0 {
                    let px = cur_x + col;
                    let py = start_y + row as i32;
                    if px >= 0 && py >= 0 && (px as u32) < stride && (py as u32) < max_h {
                        buffer[(py as u32 * stride + px as u32) as usize] = color;
                    }
                }
            }
        }
        cur_x += 6; // 5px glyph + 1px spacing
    }
}

/// Measures text width in pixels using 5x7 font (6px per char).
pub fn measure_text_width(text: &str) -> u32 {
    (text.len() as u32) * 6
}

/// Renders a floating tooltip pill with rounded corners, subtle drop border, and glowing text.
pub fn draw_tooltip_pill(
    buffer: &mut [u32],
    stride: u32,
    max_h: u32,
    text: &str,
    x: i32,
    y: i32,
) {
    let text_w = measure_text_width(text);
    let pill_w = (text_w + 14) as i32;
    let pill_h = 22i32;

    let x0 = x.clamp(4, stride as i32 - pill_w - 4);
    let y0 = y.clamp(4, max_h as i32 - pill_h - 4);
    let x1 = x0 + pill_w;
    let y1 = y0 + pill_h;

    let bg_color: u32 = 0xEE161923;    // Sleek dark translucent slate
    let border_color: u32 = 0xFF4A5578;// Subtle slate-blue accent border
    let text_color: u32 = 0xFFF8FAFC;  // Crisp white

    // Fill pill with rounded corner cuts
    for py in y0..y1 {
        if py < 0 || (py as u32) >= max_h { continue; }
        let row_offset = (py as u32 * stride) as usize;
        for px in x0..x1 {
            if px < 0 || (px as u32) >= stride { continue; }
            let is_corner = (px == x0 && (py == y0 || py == y1 - 1))
                || (px == x1 - 1 && (py == y0 || py == y1 - 1));
            if is_corner { continue; }

            let is_border = px == x0 || px == x1 - 1 || py == y0 || py == y1 - 1
                || (px == x0 + 1 && (py == y0 || py == y1 - 1))
                || (px == x1 - 2 && (py == y0 || py == y1 - 1));

            buffer[row_offset + px as usize] = if is_border { border_color } else { bg_color };
        }
    }

    // Render text centered inside pill
    render_text_to_buffer(buffer, stride, max_h, text, x0 + 7, y0 + 7, text_color);
}

